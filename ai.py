def _history_to_transcript(history: list[dict]) -> str:
    speakers = {"user": "Клиент", "assistant": "Консультант", "manager": "Консультант"}
    return "\n".join(f"{speakers.get(msg['role'], msg['role'])}: {msg['content']}" for msg in history)


def _empty_analysis() -> dict:
    return {
        "name": None,
        "interest": None,
        "ready_to_order": False,
        "asks_question": False,
        "needs_human": False,
        "human_reason": None,
        "confirmation": None,
        "corrections": {"name": None, "interest": None},
    }


def _str_or_none(value) -> str | None:
    if isinstance(value, str) and value.strip() and value.strip().lower() != "null":
        return value.strip()
    return None


async def analyze_message(
    history: list[dict], profile: dict | None = None, awaiting_confirmation: bool = False
) -> dict:
    """
    Один лёгкий запрос, который разбирает последнее сообщение клиента: имя/услуга,
    готов ли заказать, нужен ли живой человек (и почему), а если клиенту показана
    карточка заявки — подтвердил он её, исправил, отказался или спросил о другом.
    Шлём как один текстовый блок, а не как чат: Gemini не принимает запрос,
    где последняя реплика — от модели.
    """
    result = _empty_analysis()
    if not history:
        return result

    system = ANALYZE_SYSTEM_PROMPT
    if awaiting_confirmation and profile:
        system += CONFIRM_ANALYZE_BLOCK.format(
            name=profile.get("name") or "—",
            phone=profile.get("phone") or "—",
            interest=profile.get("interest") or "—",
        )

    response = await _generate_with_retry(
        model=MODEL,
        contents=_history_to_transcript(history),
        config=types.GenerateContentConfig(
            system_instruction=system,
            max_output_tokens=1000,
            response_mime_type="application/json",
        ),
    )
    raw = (response.text or "").strip()
    raw = raw.removeprefix("```json").removeprefix("```").removesuffix("```").strip()
    try:
        data = json.loads(raw)
    except json.JSONDecodeError:
        logging.warning("Анализ сообщения вернул не JSON: %s", raw[:300])
        return result
    if not isinstance(data, dict):
        return result

    result["name"] = _str_or_none(data.get("name"))
    result["interest"] = _str_or_none(data.get("interest"))
    result["ready_to_order"] = data.get("ready_to_order") is True
    result["asks_question"] = data.get("asks_question") is True
    result["needs_human"] = data.get("needs_human") is True
    if result["needs_human"]:
        result["human_reason"] = _str_or_none(data.get("human_reason")) or "Нужна помощь менеджера"
    if awaiting_confirmation:
        action = data.get("confirmation")
        result["confirmation"] = action if action in _CONFIRMATION_ACTIONS else "other"
        corrections = data.get("corrections") if isinstance(data.get("corrections"), dict) else {}
        result["corrections"] = {
            "name": _str_or_none(corrections.get("name")),
            "interest": _str_or_none(corrections.get("interest")),
        }
    return result
