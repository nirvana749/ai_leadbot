# Сетевые заминки и временные сбои Gemini (таймаут, 5xx, обрыв соединения) не должны
# сразу превращаться в "техническую заминку" для клиента — тихо повторяем пару раз
# с нарастающей паузой и только потом отдаём ошибку наверх.
_GENERATE_ATTEMPTS = 3
_RETRY_BASE_DELAY = 1.0


async def _generate_with_retry(**kwargs):
    last_exc: Exception | None = None
    for attempt in range(_GENERATE_ATTEMPTS):
        try:
            return await client.aio.models.generate_content(**kwargs)
        except Exception as exc:
            last_exc = exc
            if attempt < _GENERATE_ATTEMPTS - 1:
                delay = _RETRY_BASE_DELAY * (2 ** attempt)
                logging.warning(
                    "Gemini запрос упал (попытка %s/%s), повтор через %.1fс: %s",
                    attempt + 1, _GENERATE_ATTEMPTS, delay, exc,
                )
                await asyncio.sleep(delay)
    raise last_exc


