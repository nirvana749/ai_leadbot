def _to_gemini_contents(history: list[dict]) -> list[types.Content]:
    """Наш формат {"role": "user"/"assistant", "content": "..."} -> формат Gemini."""
    contents = []
    for msg in history:
        # "manager" — сообщения, которые владелец сам написал клиенту: для ИИ это тоже реплики консультанта
        role = "model" if msg["role"] in ("assistant", "manager") else "user"
        contents.append(types.Content(role=role, parts=[types.Part(text=msg["content"])]))
    return contents


MODEL = "gemini-flash-lite-latest"  # облегчённая модель: быстрее и с намного большей бесплатной квотой


def _known_profile_block(profile: dict | None) -> str:
    """
    Явно говорим модели, что уже известно о клиенте. Полагаться на то, что модель сама
    заметит имя в истории переписки, ненадёжно — она может переспросить его повторно,
    особенно если клиент несколько раз менял тему разговора.
    """
    if not profile:
        return ""
    known = []
    if profile.get("name"):
        known.append(f"имя — {profile['name']}")
    if profile.get("interest"):
        known.append(f"интересует — {profile['interest']}")
    if profile.get("phone"):
        known.append(f"телефон — {profile['phone']}")
    if not known:
        return ""
    return "\n\nУже известно о клиенте: " + "; ".join(known) + ". Это уже спрошено — не спрашивай повторно."


async def ask_ai(history: list[dict], profile: dict | None = None) -> str:
    response = await _generate_with_retry(
        model=MODEL,
        contents=_to_gemini_contents(history),
        config=types.GenerateContentConfig(
            system_instruction=SYSTEM_PROMPT + _known_profile_block(profile),
            max_output_tokens=350,  # держим ответы короткими, это чат, а не письмо
        ),
    )
    return response.text


async def ask_followup(history: list[dict], profile: dict | None = None) -> str:
    """Мягкое сообщение-напоминание, когда клиент сказал 'подумаю' и надолго замолчал."""
